"""Live sessions: creation, lookup, expiry and limits.

Adapters (REST, MCP, web UI) talk only to this class and to the `Session` it returns.
Sessions live in process memory; their trajectories are written to disk as they happen, so a
trajectory stays downloadable after its session ends. Served images are deleted when a session
ends (they can be regenerated by replaying the trajectory).
"""

from __future__ import annotations

import json
import math
import os
import re
import tempfile
import threading
import time
import uuid
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from slidetwin.core.config import ConfigStore, Profile, Protocol
from slidetwin.core.errors import (
    ConfigError,
    InvalidParameter,
    SessionNotFound,
    SlideNotFound,
    TooManySessions,
)
from slidetwin.core.images import DiskImageStore, ImageStore, MemoryImageStore
from slidetwin.core.registry import SlideRegistry
from slidetwin.core.session import Session, check_actor, check_viewport

SESSION_ID_RE = re.compile(r"[0-9a-f]{32}")


@dataclass
class _Entry:
    session: Session
    created: float
    last_used: float


class SessionManager:
    def __init__(
        self,
        *,
        registry: SlideRegistry,
        configs: ConfigStore,
        log_dir: Path | None = None,
        max_sessions: int = 16,
        idle_ttl_s: float = 7200.0,
        max_age_s: float = 28800.0,
        evict_idle_s: float = 900.0,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        if max_sessions < 1:
            raise ValueError("max_sessions must be >= 1")
        checked = (
            ("idle_ttl_s", idle_ttl_s),
            ("max_age_s", max_age_s),
            ("evict_idle_s", evict_idle_s),
        )
        for name, value in checked:
            if not (math.isfinite(value) and value > 0):
                raise ValueError(f"{name} must be a positive number")
        self.registry = registry
        self.configs = configs
        self.log_dir = log_dir
        self.max_sessions = max_sessions
        self.idle_ttl_s = idle_ttl_s
        self.max_age_s = max_age_s
        # When every slot is taken, a session idle this long may give its slot to a new one, so
        # abandoned tabs cannot block a public server until the idle TTL. Its log stays on disk.
        self.evict_idle_s = evict_idle_s
        self._clock = clock
        self._sessions: dict[str, _Entry] = {}
        self._pending = 0  # slots reserved by creations in progress
        self._lock = threading.Lock()

    def __len__(self) -> int:
        with self._lock:
            return len(self._sessions)

    # --- catalogue (public payloads, built here so every adapter serves the same) ----------------

    def catalogue(self) -> list[dict[str, Any]]:
        return self.registry.catalogue()

    def profiles(self) -> list[dict[str, Any]]:
        return [p.model_dump(mode="json") for p in self.configs.profiles.values()]

    def protocols(self) -> list[dict[str, Any]]:
        return [p.task_description() for p in self.configs.protocols.values()]

    # --- sessions --------------------------------------------------------------------------------

    def create(
        self,
        *,
        slide_id: str,
        actor: str,
        profile: str = "viewer",
        protocol: str = "sln_metastasis",
        viewport_px: Sequence[int] | None = None,
        view_format: str = "jpeg",
        store_images: bool = True,
    ) -> Session:
        """A new session. `view_format` "array" serves RGB arrays instead of JPEGs, and without
        `store_images` no served JPEG is kept for later GETs (both for the training interface;
        REST and MCP always serve and keep JPEGs)."""
        prof: Profile = self._lookup(self.configs.profile, profile)
        proto: Protocol = self._lookup(self.configs.protocol, protocol)
        check_actor(actor)
        check_viewport(viewport_px, prof.viewport_default_px)
        if slide_id not in self.registry.ids():
            raise SlideNotFound(
                f"Unknown slide {slide_id[:64]!r}.",
                hint="List the available slides with GET /api/slides.",
            )
        with self._lock:
            ended = self._sweep_locked()
            if len(self._sessions) + self._pending >= self.max_sessions:
                ended += self._evict_closed_locked()
            if len(self._sessions) + self._pending >= self.max_sessions:
                ended += self._evict_idle_locked()
            full = len(self._sessions) + self._pending >= self.max_sessions
            if not full:
                self._pending += 1
        self._dispose(ended)
        if full:
            raise TooManySessions(
                f"All {self.max_sessions} session slots are in use.",
                hint="Submit the report of an open session, or try again in a few minutes.",
            )
        session_id = uuid.uuid4().hex
        images = self._image_store(session_id)
        try:
            slide = self.registry.get(slide_id)
            session = Session(
                session_id=session_id,
                slide_id=slide.slide_id,
                source=slide.source,
                slide_sha256=slide.sha256,
                slide_fileset_sha256=slide.fileset_sha256,
                profile=prof,
                protocol=proto,
                actor=actor,
                images=images,
                viewport_px=viewport_px,
                log_path=self._log_path(session_id),
                view_format=view_format,
                store_images=store_images,
            )
        except BaseException:
            images.discard()
            log = self._log_path(session_id)
            if log is not None:
                log.unlink(missing_ok=True)  # the session never started
            with self._lock:
                self._pending -= 1
            raise
        now = self._clock()
        with self._lock:
            self._pending -= 1
            self._sessions[session_id] = _Entry(session, now, now)
        return session

    def get(self, session_id: str, *, touch: bool = True) -> Session:
        """Look up a live session. Only actions (`touch=True`) count as activity; downloads of
        images or the trajectory do not keep a session alive."""
        with self._lock:
            ended = self._sweep_locked()
            entry = (
                self._sessions.get(session_id)
                if isinstance(session_id, str) and SESSION_ID_RE.fullmatch(session_id)
                else None
            )
            if entry is not None and touch:
                entry.last_used = self._clock()
        self._dispose(ended)
        if entry is None:
            hint = (
                "Create a new session; an ended session's trajectory can still be downloaded."
                if self.log_dir is not None
                else "Create a new session."
            )
            raise SessionNotFound(
                f"Session {str(session_id)[:40]!r} does not exist or has ended.", hint=hint
            )
        return entry.session

    def trajectory(self, session_id: str) -> str:
        """JSONL of a live session (logged as export_trajectory) or of an ended one from disk."""
        try:
            session = self.get(session_id, touch=False)
        except SessionNotFound:
            path = self._log_path(session_id) if SESSION_ID_RE.fullmatch(session_id) else None
            if path is None or not path.is_file():
                raise
            return path.read_text(encoding="ascii")
        return session.export_trajectory().text or ""

    def save_feedback(self, session_id: str, feedback: dict[str, Any]) -> None:
        """Store a reader's feedback on a session (pilot studies) next to the session's log. It is
        not part of the trajectory and changes nothing in the session."""
        path = self._log_path(session_id) if SESSION_ID_RE.fullmatch(str(session_id)) else None
        with self._lock:
            live = session_id in self._sessions
        if path is None or not (live or path.is_file()):
            raise SessionNotFound(
                f"Session {str(session_id)[:40]!r} does not exist.",
                hint="Feedback is stored with a session this server ran and logged.",
            )
        record = {"session_id": session_id, "received_utc": datetime.now(UTC).isoformat()}
        target = path.parent.parent / "feedback" / f"{session_id}.json"
        target.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=target.parent, prefix=".feedback.")
        with os.fdopen(fd, "w", encoding="ascii") as f:
            json.dump({**record, **feedback}, f, ensure_ascii=True, indent=1)
        os.replace(tmp, target)

    def sweep(self) -> None:
        with self._lock:
            ended = self._sweep_locked()
        self._dispose(ended)

    def end(self, session_id: str) -> None:
        """End one session now, as its expiry would: its log stays, its served images go."""
        with self._lock:
            entry = self._sessions.pop(session_id, None)
        if entry is not None:
            self._dispose([entry.session])

    def close_all(self) -> None:
        with self._lock:
            ended = [e.session for e in self._sessions.values()]
            self._sessions.clear()
        self._dispose(ended)

    # --- helpers -------------------------------------------------------------------------------

    @staticmethod
    def _lookup(fn: Callable[[str], Any], key: str) -> Any:
        try:
            return fn(key)
        except ConfigError as err:
            raise InvalidParameter(err.message) from None

    def _sweep_locked(self) -> list[Session]:
        now = self._clock()
        expired = [
            k
            for k, e in self._sessions.items()
            if now - e.last_used > self.idle_ttl_s or now - e.created > self.max_age_s
        ]
        return [self._sessions.pop(k).session for k in expired]

    def _evict_closed_locked(self) -> list[Session]:
        closed = sorted((e.last_used, k) for k, e in self._sessions.items() if e.session.closed)
        excess = len(self._sessions) + self._pending - self.max_sessions + 1
        return [self._sessions.pop(k).session for _, k in closed[:excess]]

    def _evict_idle_locked(self) -> list[Session]:
        """The least recently used session idle for at least `evict_idle_s`, if any."""
        now = self._clock()
        idle = sorted(
            (e.last_used, k)
            for k, e in self._sessions.items()
            if now - e.last_used >= self.evict_idle_s
        )
        return [self._sessions.pop(k).session for _, k in idle[:1]]

    @staticmethod
    def _dispose(sessions: list[Session]) -> None:
        """End sessions outside the manager lock: close() waits for an action in progress."""
        for session in sessions:
            session.close()
            session.discard_images()

    def _log_path(self, session_id: str) -> Path | None:
        if self.log_dir is None:
            return None
        return self.log_dir / "sessions" / f"{session_id}.jsonl"

    def _image_store(self, session_id: str) -> ImageStore:
        if self.log_dir is None:
            return MemoryImageStore()
        return DiskImageStore(self.log_dir / "sessions" / session_id)
